def with_extra(calendar_id: str, blocks: list[dict]) -> list[dict]:
    """Insert EXTRA_SECTIONS before the first links block (or before FAQ)."""
    extra = list(EXTRA_SECTIONS.get(calendar_id) or [])
    extra.extend(BONUS_SECTIONS.get(calendar_id) or [])
    if not extra:
        return blocks
    out: list[dict] = []
    inserted = False
    for b in blocks:
        if not inserted and b.get("type") in {"links", "faq"}:
            out.extend(extra)
            inserted = True
        out.append(b)
    if not inserted:
        out.extend(extra)
    return out



