def meta(seo_title: str, seo_description: str) -> dict:
    return {"type": "meta", "seo_title": seo_title, "seo_description": seo_description}


def p(text: str) -> dict:
    return {"type": "paragraph", "text": text}


def h(text: str) -> dict:
    return {"type": "heading", "text": text}


def sh(text: str) -> dict:
    return {"type": "subheading", "text": text}


def ul(items: list[str]) -> dict:
    return {"type": "list", "items": items}


def ol(items: list[str]) -> dict:
    return {"type": "list", "ordered": True, "items": items}


def tip(text: str) -> dict:
    return {"type": "callout", "variant": "tip", "text": text}


def note(text: str) -> dict:
    return {"type": "callout", "variant": "note", "text": text}


def warn(text: str) -> dict:
    return {"type": "callout", "variant": "warning", "text": text}


def links(items: list[tuple[str, str]], title: str = "مسیرهای مرتبط در کارزار") -> dict:
    return {
        "type": "links",
        "title": title,
        "items": [{"href": href, "label": label} for href, label in items],
    }


def faq(items: list[tuple[str, str]]) -> dict:
    return {
        "type": "faq",
        "items": [{"question": q, "answer": a} for q, a in items],
    }



